-- 确认订单信息表（附表 / 工作台任务表）
-- 说明：
--   1. 原 7E4 表 ConfirmationOrderInfo7E4 保持不动，本表是其“任务化”附表；
--   2. 业务字段沿用 7E4 口径（平台订单号/子订单号/下单时间/买家/收件人/SKU 等），改为下划线命名；
--   3. 新增指派、处理状态、处理标记、导入批次等任务字段；
--   4. biz_key 为幂等键：优先子订单号，其次平台订单号，导表按它 upsert（更新业务字段、不覆盖任务字段）。
CREATE TABLE IF NOT EXISTS `OrderInfoToConfirm` (
  `id` int NOT NULL AUTO_INCREMENT,
  `biz_key` varchar(160) NOT NULL COMMENT '业务唯一键（子订单号优先，否则平台订单号）',
  `platform_order_id` varchar(64) DEFAULT NULL COMMENT '平台订单编号',
  `platform_sub_order_id` varchar(64) DEFAULT NULL COMMENT '子订单编号',
  `origin_order_id` varchar(64) DEFAULT NULL COMMENT '原始平台订单号 orderItem_originOrderId',
  `shop_name` varchar(100) DEFAULT NULL COMMENT '店铺',
  `order_status` varchar(64) DEFAULT NULL COMMENT '平台订单状态',
  `sub_order_status` varchar(64) DEFAULT NULL COMMENT '子订单状态',
  `purchase_date` datetime DEFAULT NULL COMMENT '下单时间',
  `payments_date` datetime DEFAULT NULL COMMENT '付款时间',
  `buyer_email` varchar(255) DEFAULT NULL COMMENT '买家邮箱',
  `buyer_phone` varchar(50) DEFAULT NULL COMMENT '买家电话',
  `recipient_name` varchar(100) DEFAULT NULL COMMENT '收件人',
  `ship_address_1` varchar(255) DEFAULT NULL COMMENT '收件地址1',
  `ship_address_2` varchar(255) DEFAULT NULL COMMENT '收件地址2',
  `ship_city` varchar(100) DEFAULT NULL COMMENT '收件城市',
  `ship_state` varchar(100) DEFAULT NULL COMMENT '收件州/省',
  `ship_postal_code` varchar(20) DEFAULT NULL COMMENT '邮编',
  `sku` varchar(100) DEFAULT NULL COMMENT 'SKU',
  `quantity_purchased` int DEFAULT NULL COMMENT '数量',
  `item_price` decimal(10,2) DEFAULT NULL COMMENT '商品金额',
  `category` varchar(100) DEFAULT NULL COMMENT '品类',
  `wicker_color` varchar(50) DEFAULT NULL COMMENT '藤条颜色',
  `cushion_color` varchar(50) DEFAULT NULL COMMENT '坐垫颜色',
  `priority_of_shipment` varchar(50) DEFAULT NULL COMMENT '发货优先级',
  `order_remark` varchar(500) DEFAULT NULL COMMENT '订单备注',
  `assignee_id` int DEFAULT NULL COMMENT '负责人 ID（NocoBase users.id）',
  `assignee_name` varchar(64) DEFAULT NULL COMMENT '负责人姓名',
  `assign_status` varchar(20) NOT NULL DEFAULT '未指派' COMMENT '指派状态：未指派/已指派',
  `assigned_at` datetime DEFAULT NULL COMMENT '指派时间',
  `assigned_by` varchar(64) DEFAULT NULL COMMENT '指派人',
  `handle_status` varchar(20) NOT NULL DEFAULT '未处理' COMMENT '处理状态：未处理/已处理/待跟踪',
  `handle_mark` varchar(50) DEFAULT NULL COMMENT '处理标记：已发手工咨询/顾客已确认原样发货/顾客已确认修改发货/确认未果原样发货/确认未果修改发货/取消订单',
  `handle_note` varchar(1000) DEFAULT NULL COMMENT '处理备注',
  `handled_at` datetime DEFAULT NULL COMMENT '处理时间',
  `handled_by` varchar(64) DEFAULT NULL COMMENT '处理人',
  `import_batch` varchar(64) DEFAULT NULL COMMENT '导入批次',
  `source` varchar(20) NOT NULL DEFAULT 'excel' COMMENT '数据来源：excel/api',
  `imported_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '首次导入/创建时间',
  `last_import_at` datetime DEFAULT NULL COMMENT '最近一次导入时间',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_biz_key` (`biz_key`),
  KEY `idx_platform_order` (`platform_order_id`),
  KEY `idx_sub_order` (`platform_sub_order_id`),
  KEY `idx_purchase_date` (`purchase_date`),
  KEY `idx_imported_at` (`imported_at`),
  KEY `idx_last_import` (`last_import_at`),
  KEY `idx_assignee` (`assignee_id`),
  KEY `idx_handle_status` (`handle_status`),
  KEY `idx_handle_mark` (`handle_mark`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='确认订单信息表（工作台附表）';
